import React from 'react';
import { AlertTriangle, CheckCircle2, Clock, Zap, Cpu, Send, ChevronRight, Activity, MapPin, Sliders, Radio } from 'lucide-react';

export default function MachineCard({
  machine,
  currentRole,
  onOpenDetails,
  onOpenShap,
  onOpenRul,
  onOpenSendAlert,
  onOpenManualPrediction
}) {
  const {
    id,
    name,
    industry,
    type,
    location,
    readings,
    prediction_rf,
    prediction_xgb,
    consensus,
    rul,
    telemetry_source = 'SIMULATED',
    connection_status = 'SIMULATED',
    feature_compatibility,
    sensor_definitions
  } = machine;

  const isCritical = consensus.status === 'Critical';
  const isWarning = consensus.status === 'Warning';
  const isHealthy = consensus.status === 'Healthy';

  const telemetryBadge = telemetry_source === 'HARDWARE' ? (
    <span className="px-2 py-0.5 rounded-full text-[10px] font-mono font-bold flex items-center gap-1 bg-emerald-500/20 border border-emerald-500/50 text-emerald-300" title="Live stream from real physical hardware or IoT gateway">
      <Radio className="w-3 h-3 text-emerald-400 animate-pulse" />
      LIVE HARDWARE
    </span>
  ) : telemetry_source === 'MANUAL' ? (
    <span className="px-2 py-0.5 rounded-full text-[10px] font-mono font-bold flex items-center gap-1 bg-purple-500/20 border border-purple-500/50 text-purple-300" title="Manual test readings applied by operator">
      <Sliders className="w-3 h-3 text-purple-400" />
      MANUAL OVERRIDE
    </span>
  ) : (
    <span className="px-2 py-0.5 rounded-full text-[10px] font-mono font-medium flex items-center gap-1 bg-amber-500/15 border border-amber-500/40 text-amber-300" title="Simulated readings generated by synthetic industrial simulation engine">
      <Activity className="w-3 h-3 text-amber-400" />
      SIMULATED
    </span>
  );

  const statusBadge = isCritical ? (
    <span className="px-2.5 py-1 rounded-full text-xs font-mono font-bold flex items-center gap-1.5 bg-rose-500/15 border border-rose-500/40 text-rose-400 shadow-rose-glow">
      <AlertTriangle className="w-3.5 h-3.5 text-rose-400 animate-pulse" />
      CRITICAL
    </span>
  ) : isWarning ? (
    <span className="px-2.5 py-1 rounded-full text-xs font-mono font-bold flex items-center gap-1.5 bg-amber-500/15 border border-amber-500/40 text-amber-400">
      <AlertTriangle className="w-3.5 h-3.5 text-amber-400" />
      WARNING
    </span>
  ) : (
    <span className="px-2.5 py-1 rounded-full text-xs font-mono font-bold flex items-center gap-1.5 bg-emerald-500/15 border border-emerald-500/40 text-emerald-400">
      <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" />
      HEALTHY
    </span>
  );

  const healthBarGradient = isCritical
    ? 'from-rose-600 to-red-500'
    : isWarning
    ? 'from-amber-500 to-orange-500'
    : 'from-emerald-500 to-cyan-500';

  const healthTextColor = isCritical
    ? 'text-rose-400'
    : isWarning
    ? 'text-amber-400'
    : 'text-emerald-400';

  return (
    <div className="card-glass relative flex flex-col justify-between rounded-2xl p-5 transition-all duration-300 hover:scale-[1.01] group">
      
      {/* Top Header */}
      <div>
        <div className="flex items-start justify-between gap-3 mb-2">
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <span className="text-xs font-mono font-semibold px-2 py-0.5 rounded-md bg-slate-800/90 border border-slate-700/80 text-cyan-300">
                {id}
              </span>
              <span className="text-[11px] font-medium text-slate-400">
                {industry} &bull; {type}
              </span>
              {telemetryBadge}
            </div>
            <h3 className="text-base font-bold text-white mt-1.5 group-hover:text-cyan-300 transition-colors">
              {name}
            </h3>
            {location && (
              <div className="flex items-center gap-1 text-[11px] font-mono text-slate-400 mt-0.5">
                <MapPin className="w-3 h-3 text-cyan-400 shrink-0" />
                <span className="truncate">{location}</span>
              </div>
            )}
          </div>

          {/* Status Badge */}
          <div className="flex flex-col items-end">
            {statusBadge}
            <span className="text-[10px] font-mono text-slate-400 mt-1">
              Risk: <strong className={healthTextColor}>{consensus.risk_level}</strong>
            </span>
          </div>
        </div>

        {/* Health Score Progress Bar */}
        <div className="my-3 bg-slate-950/60 p-3 rounded-xl border border-slate-800/70">
          <div className="flex justify-between items-center text-xs font-medium mb-1.5">
            <span className="text-slate-300">Machine Health Score</span>
            <span className={`font-mono font-bold text-sm ${healthTextColor}`}>{consensus.health_score}%</span>
          </div>
          <div className="w-full bg-slate-900 h-2 rounded-full overflow-hidden border border-slate-800">
            <div
              className={`h-full bg-gradient-to-r ${healthBarGradient} transition-all duration-500`}
              style={{ width: `${consensus.health_score}%` }}
            />
          </div>
        </div>

        {/* Dual ML Model Predictions: Random Forest vs XGBoost */}
        <div className="grid grid-cols-2 gap-2.5 my-3">
          <div className="bg-slate-950/80 p-3 rounded-xl border border-slate-800/80 hover:border-cyan-500/30 transition-colors">
            <div className="flex items-center justify-between text-[11px] font-medium text-cyan-400 mb-1">
              <span>XGBoost</span>
              <span className="text-[10px] font-mono px-1.5 py-0.2 rounded bg-cyan-950/60 text-cyan-300 border border-cyan-800/50">
                Gradient Tree
              </span>
            </div>
            <div className="text-xl font-black font-mono text-white">
              {prediction_xgb.failure_probability}%
            </div>
            <div className="text-[10px] font-mono text-slate-400 mt-0.5">
              Failure Probability
            </div>
          </div>

          <div className="bg-slate-950/80 p-3 rounded-xl border border-slate-800/80 hover:border-indigo-500/30 transition-colors">
            <div className="flex items-center justify-between text-[11px] font-medium text-indigo-400 mb-1">
              <span>Random Forest</span>
              <span className="text-[10px] font-mono px-1.5 py-0.2 rounded bg-indigo-950/60 text-indigo-300 border border-indigo-800/50">
                Ensemble
              </span>
            </div>
            <div className="text-xl font-black font-mono text-white">
              {prediction_rf.failure_probability}%
            </div>
            <div className="text-[10px] font-mono text-slate-400 mt-0.5">
              Failure Probability
            </div>
          </div>
        </div>

        {/* Remaining Useful Life (RUL) Summary */}
        <div className="bg-slate-950/60 p-3 rounded-xl border border-slate-800/80 flex items-center justify-between my-3">
          <div className="flex items-center gap-2.5">
            <div className="p-1.5 rounded-lg bg-cyan-950/60 text-cyan-400 border border-cyan-800/40">
              <Clock className="w-4 h-4" />
            </div>
            <div>
              <div className="text-[11px] font-medium text-slate-400">Estimated RUL</div>
              <div className="text-sm font-bold text-white font-mono">
                {rul.hours} <span className="text-xs text-slate-400 font-normal">Hours</span>
                <span className="text-xs text-slate-500 ml-2">({rul.cycles} cycles)</span>
              </div>
            </div>
          </div>
          <button
            onClick={() => onOpenRul(machine)}
            className="text-xs font-mono font-medium text-cyan-400 hover:text-cyan-300 hover:underline flex items-center gap-1"
          >
            <span>Trajectory</span>
            <ChevronRight className="w-3.5 h-3.5" />
          </button>
        </div>

        {/* Feature Compatibility Notice if non-AI4I sensors configured */}
        {feature_compatibility && !feature_compatibility.is_compatible && (
          <div className="my-2.5 p-2.5 rounded-xl bg-amber-950/40 border border-amber-500/40 text-[11px] font-mono text-amber-300 flex items-start gap-2">
            <AlertTriangle className="w-4 h-4 text-amber-400 shrink-0 mt-0.5" />
            <div>
              <strong className="block text-amber-200">Custom Sensor Topology:</strong>
              <span>{feature_compatibility.message}</span>
            </div>
          </div>
        )}

        {/* Current Sensor Telemetry (Machine Specific) */}
        <div className="bg-slate-950/80 p-3.5 rounded-xl border border-slate-800/60 my-2">
          <div className="flex items-center justify-between text-[11px] font-mono font-semibold uppercase tracking-wider mb-2.5">
            <span className="text-slate-400">Sensor Telemetry Feed</span>
            <span className="text-[10px] font-normal text-slate-400">
              Source: <strong className={telemetry_source === 'HARDWARE' ? 'text-emerald-400 font-bold' : telemetry_source === 'MANUAL' ? 'text-purple-300 font-bold' : 'text-amber-400 font-medium'}>
                {telemetry_source === 'HARDWARE' ? 'Live IoT Stream' : telemetry_source === 'MANUAL' ? 'Manual Override' : 'Synthetic Simulation'}
              </strong>
            </span>
          </div>
          <div className="grid grid-cols-2 gap-x-3 gap-y-2 text-xs font-mono">
            {(sensor_definitions && sensor_definitions.length > 0 ? sensor_definitions : [
              { key: 'air_temperature_k', label: 'Air Temp', unit: 'K' },
              { key: 'process_temperature_k', label: 'Proc Temp', unit: 'K' },
              { key: 'rotational_speed_rpm', label: 'Spindle/Rot', unit: 'RPM' },
              { key: 'torque_nm', label: 'Torque', unit: 'Nm' },
              { key: 'tool_wear_min', label: 'Tool Wear', unit: 'min' }
            ]).map((s, idx, arr) => {
              const val = readings[s.key] !== undefined ? readings[s.key] : '--';
              const isFullWidth = idx === arr.length - 1 && arr.length % 2 !== 0;
              const isHighlight = s.key === 'tool_wear_min' && val > 200;
              return (
                <div key={s.key} className={`flex justify-between border-b border-slate-850 pb-1.5 ${isFullWidth ? 'col-span-2' : ''}`}>
                  <span className="text-slate-400 truncate pr-1" title={s.label || s.key}>
                    {s.label || s.key}:
                  </span>
                  <span className={`font-medium whitespace-nowrap ${isHighlight ? 'text-rose-400 font-bold' : 'text-slate-200'}`}>
                    {val} {s.unit || ''}
                  </span>
                </div>
              );
            })}
          </div>
        </div>
      </div>

      {/* Role Action Controls */}
      <div className="mt-4 pt-3.5 border-t border-slate-800/80 flex flex-col gap-2">
        {currentRole === 'organiser' ? (
          /* Organiser Actions */
          <div className="flex items-center gap-2">
            <button
              onClick={() => onOpenSendAlert(machine)}
              className="flex-1 flex items-center justify-center gap-2 px-3 py-2.5 rounded-xl bg-gradient-to-r from-indigo-600 to-indigo-500 hover:from-indigo-500 hover:to-indigo-400 text-white font-medium text-xs transition-all shadow-indigo-glow"
              title="Dispatch urgent alert to worker (nukameghan@gmail.com)"
            >
              <Send className="w-3.5 h-3.5" />
              <span>Send Alert</span>
            </button>
            {onOpenManualPrediction && (
              <button
                onClick={() => onOpenManualPrediction(machine)}
                className="px-3 py-2.5 rounded-xl bg-slate-800/80 hover:bg-slate-700 text-cyan-300 font-medium text-xs border border-slate-700/80 transition-colors flex items-center gap-1"
                title="Manual Sensor Prediction"
              >
                <Sliders className="w-3.5 h-3.5" />
                <span>Predict</span>
              </button>
            )}
            <button
              onClick={() => onOpenDetails(machine)}
              className="px-3 py-2.5 rounded-xl bg-slate-800/80 hover:bg-slate-700 text-slate-200 font-medium text-xs border border-slate-700/80 transition-colors"
              title="Inspect machine"
            >
              Details
            </button>
          </div>
        ) : (
          /* Worker Actions */
          <div className="flex items-center gap-2">
            <button
              onClick={() => onOpenShap(machine)}
              className="flex-1 flex items-center justify-center gap-2 px-3 py-2.5 rounded-xl bg-gradient-to-r from-cyan-600 to-cyan-500 hover:from-cyan-500 hover:to-cyan-400 text-white font-medium text-xs transition-all shadow-cyan-glow"
              title="View SHAP feature impact explanation"
            >
              <Zap className="w-3.5 h-3.5 text-cyan-200" />
              <span>Explain SHAP</span>
            </button>
            {onOpenManualPrediction && (
              <button
                onClick={() => onOpenManualPrediction(machine)}
                className="px-3 py-2.5 rounded-xl bg-slate-800/80 hover:bg-slate-700 text-cyan-300 font-medium text-xs border border-slate-700/80 transition-colors flex items-center gap-1"
                title="Manual Sensor Prediction"
              >
                <Sliders className="w-3.5 h-3.5" />
                <span>Predict</span>
              </button>
            )}
            <button
              onClick={() => onOpenDetails(machine)}
              className="px-3 py-2.5 rounded-xl bg-slate-800/80 hover:bg-slate-700 text-slate-200 font-medium text-xs border border-slate-700/80 transition-colors"
            >
              Telemetry
            </button>
          </div>
        )}
      </div>

    </div>
  );
}
